def haversine(lat1, lon1, lat2, lon2):
    """
    Calculate the great-circle distance between two points on Earth.
    Inputs are in decimal degrees.
    Returns distance in kilometers.
    """
    # Convert decimal degrees to radians
    lat1, lon1, lat2, lon2 = map(math.radians, [lat1, lon1, lat2, lon2])

    # Haversine formula
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = math.sin(dlat / 2)**2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2)**2
    c = 2 * math.asin(math.sqrt(a))
    r = 6371.0088  # Earth's radius in kilometers
    return r * c

def path_length(coords):
    """
    Calculate total path length from a list of (lat, lon) tuples.
    """
    if not coords or len(coords) < 2:
        return 0.0  # No distance if less than 2 points

    total_distance = 0.0
    l = 0.0
    for i in range(len(coords) - 1):
        lat1, lon1 = coords[i]
        lat2, lon2 = coords[i + 1]
        total_distance += haversine(lat1, lon1, lat2, lon2)
        l += math.sqrt(abs(lon2 - lon1)**2 + abs(lat2 - lat1)**2)
    return [total_distance, l]

